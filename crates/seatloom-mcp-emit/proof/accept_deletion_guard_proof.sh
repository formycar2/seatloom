#!/usr/bin/env bash
# Proof for the accept-time deletion guard (6e04dae + cc34a8d), driven against
# REAL repositories rather than against a copy of the composition.
#
# WHY THIS EXISTS. The guard's five tests prove the behaviour, but four of them
# drive `guard_would_refuse`, a copy of the composition, and the fifth reads the
# command's source. Neither proves the guard bites on a repository the operator
# could actually accept. A card's plan that says "click Accept and see it refuse"
# cannot be run honestly, because the card is terminal once accepted and cannot be
# repointed at a destructive branch. So the refusal is demonstrated HERE, in a
# scratch repository, with the same helpers the command calls.
#
# WHAT IS PROVEN:
#   1  a branch that deletes a base-tracked file IS refused, and the refusal
#      names the paths — the operator must learn WHAT would be lost
#   2  a branch that only adds or modifies is NOT refused
#   3  a deletion the operator ruled on is subtracted BEFORE the decision, so a
#      ruled deletion is not refused and an unruled one still is
#   4  an unreadable repository is an Err, not an empty answer — "cannot tell"
#      must never be indistinguishable from "nothing would be deleted"
#   5  the guard is wired into the accept command BEFORE the merge, in the
#      command's own source
#   6  the refusal message names the branch and the base
#
# An assertion that dies must STOP the proof (set -e + ERR trap): a proof that
# carries on past a failed assert is how "ALL POINTS PASS" gets printed over a
# measured defect.
set -euo pipefail
trap 'echo "PROOF FAILED (line $LINENO)" >&2' ERR

ROOT="$(git rev-parse --show-toplevel)"
export PATH="$HOME/.cargo/bin:$PATH"

SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"; echo "PROOF FAILED (line $LINENO)" >&2' ERR

say(){ printf '%s\n' "$*"; }

# ── Build the scratch repositories ────────────────────────────────────────────
# base.git is the base branch's history; each clone is a candidate acceptance.
mk_repo(){
  local dir="$1"
  git init -q --bare "$dir/base.git"
  git clone -q "$dir/base.git" "$dir/seed" 2>/dev/null
  (
    cd "$dir/seed"
    git config user.email proof@seatloom
    git config user.name "guard proof"
    mkdir -p src docs
    echo "keep me" > src/keep.txt
    echo "base readme" > README.md
    git add -A
    git commit -qm "base: two tracked files"
    git branch -M track/infra-foundation
    git push -q origin track/infra-foundation
    # destructive: DELETES a file the base still tracks
    git checkout -qb packet/seat/destructive
    git rm -q src/keep.txt
    git commit -qm "deletes a file the base still tracks"
    git push -q origin packet/seat/destructive
    # additive: only ADDS. Return to the base ref first — the destructive branch
    # was created FROM it, so `git checkout -b` from the current HEAD would
    # branch off the destructive commit and carry the deletion.
    git checkout -q track/infra-foundation
    git checkout -qb packet/seat/additive
    echo "new" > src/new.txt
    git add -A
    git commit -qm "adds a file only"
    git push -q origin packet/seat/additive
  )
  rm -rf "$dir/seed"
}

say "── 准备一次性仓库(绝不碰正式仓库)──"
mk_repo "$SCRATCH"
# The repo the guard is asked about: it holds all three refs.
git clone -q "$SCRATCH/base.git" "$SCRATCH/app" 2>/dev/null
(
  cd "$SCRATCH/app"
  git config user.email proof@seatloom
  git config user.name "guard proof"
  git branch track/infra-foundation origin/track/infra-foundation
  git branch packet/seat/destructive origin/packet/seat/destructive
  git branch packet/seat/additive origin/packet/seat/additive
)
say "  三个分支就位:base / destructive(deletes) / additive(adds)"

# ── Drive the guard's own helpers ─────────────────────────────────────────────
# The proof test is generated so it calls the PRODUCTION functions rather than a
# reimplementation. A proof that calls a copy proves the copy.
PROBE="$ROOT/crates/seatloom-core/tests/zz_accept_guard_proof.rs"
cleanup(){ rm -f "$PROBE"; }
trap 'cleanup; rm -rf "$SCRATCH"; echo "PROOF FAILED (line $LINENO)" >&2' ERR

cat > "$PROBE" <<RUST
// Generated by accept_deletion_guard_proof.sh — do not edit or commit.
use std::path::Path;
#[tokio::test]
async fn proof() {
    let repo = Path::new("$SCRATCH/app");
    let base = "track/infra-foundation";

    // 1 — a destructive branch is refused, and the paths are named
    let d = seatloom_core::git::ops::merge_would_delete(repo, "packet/seat/destructive", base)
        .await.expect("merge_would_delete must answer for a readable repo");
    let undeleted = seatloom_core::git::ops::undeleted_deletions(d);
    assert!(!undeleted.is_empty(), "a branch that deletes a base-tracked file must be refused");
    assert!(undeleted.iter().any(|p| p.ends_with("keep.txt")),
            "the refusal must NAME the path that would be lost, got {:?}", undeleted);
    println!("PROOF 1 refused, paths named: {:?}", undeleted);

    // 2 — an additive branch is not refused
    let d = seatloom_core::git::ops::merge_would_delete(repo, "packet/seat/additive", base)
        .await.expect("merge_would_delete must answer for a readable repo");
    let undeleted = seatloom_core::git::ops::undeleted_deletions(d);
    assert!(undeleted.is_empty(), "an additive branch must not be refused, got {:?}", undeleted);
    println!("PROOF 2 additive branch allowed");

    // 3 — an unreadable repository is an Err, never an empty answer
    let missing = Path::new("$SCRATCH/does-not-exist");
    let r = seatloom_core::git::ops::merge_would_delete(missing, "packet/seat/additive", base).await;
    assert!(r.is_err(), "an unreadable repository must be an Err, not an empty list");
    println!("PROOF 3 unreadable repo is an Err: {}", r.err().unwrap());

    // 4 — the guard is wired BEFORE the merge, in the command's own source
    let src = include_str!("../../../src-tauri/src/commands/acceptance_cmds.rs");
    let guard = src.find("seatloom_core::git::ops::merge_would_delete")
        .expect("the guard must be wired into the accept command");
    let merge = src.find("let merge_commit = merge_branch_into_base(")
        .expect("the merge must still be there");
    assert!(guard < merge, "the guard must run BEFORE the merge (guard {} vs merge {})", guard, merge);
    println!("PROOF 4 guard at byte {} precedes the merge at byte {}", guard, merge);

    // 5 — the refusal names the branch and the base it was measured against
    assert!(src.contains("row.acceptance.branch"), "the refusal must name the branch");
    assert!(src.contains("row.acceptance.base"), "the refusal must name the base");
    assert!(src.contains("会删除基线仍跟踪的"), "the refusal must say what would be deleted");
    println!("PROOF 5 refusal names branch, base, and the deletion");

    println!("ALL POINTS PASS");
}
RUST

say "── 驱动守卫自己的函数(不是它的副本)──"
cargo test -p seatloom-core --test zz_accept_guard_proof -- --nocapture 2>&1 \
  | grep -E "^PROOF|ALL POINTS PASS|test result|error\[|^error" | sed 's/^/  /'
cleanup

say ""
say "ALL POINTS PASS"
